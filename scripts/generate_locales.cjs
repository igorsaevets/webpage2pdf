const baseDir = path.join(__dirname, '../public/_locales');
if (!fs.existsSync(baseDir)) fs.mkdirSync(baseDir, { recursive: true });

for (const [lang, msgs] of Object.entries(locales)) {
  const langDir = path.join(baseDir, lang);
  if (!fs.existsSync(langDir)) fs.mkdirSync(langDir);
  
  const formatted = {};
  for (const [key, val] of Object.entries(msgs)) {
    formatted[key] = { message: val };
  }
  
  fs.writeFileSync(path.join(langDir, 'messages.json'), JSON.stringify(formatted, null, 2));
}

